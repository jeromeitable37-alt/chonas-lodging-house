create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists activity_logs_created_idx on public.activity_logs (created_at desc);
create index if not exists activity_logs_entity_idx on public.activity_logs (entity_type, entity_id);
alter table public.activity_logs enable row level security;
drop policy if exists activity_logs_read_admin on public.activity_logs;
create policy activity_logs_read_admin on public.activity_logs for select to authenticated using (public.is_admin());
grant select on public.activity_logs to authenticated;

create or replace function public.capture_booking_activity()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_action text;
begin
  if TG_OP = 'INSERT' then
    v_action := 'reservation_created';
  elsif TG_OP = 'UPDATE' and NEW.status is distinct from OLD.status then
    v_action := 'reservation_status_changed';
  else
    return NEW;
  end if;
  insert into public.activity_logs (actor_id, action, entity_type, entity_id, details)
  values (auth.uid(), v_action, 'booking', NEW.id::text,
    jsonb_build_object('reference', NEW.reference, 'status', NEW.status, 'room_name', NEW.room_name, 'check_in', NEW.check_in, 'check_out', NEW.check_out));
  return NEW;
end;
$$;
drop trigger if exists bookings_activity_after_insert on public.bookings;
create trigger bookings_activity_after_insert after insert on public.bookings for each row execute function public.capture_booking_activity();
drop trigger if exists bookings_activity_after_status_update on public.bookings;
create trigger bookings_activity_after_status_update after update of status on public.bookings
for each row when (OLD.status is distinct from NEW.status) execute function public.capture_booking_activity();

create or replace function public.capture_room_activity()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_action text;
begin
  if TG_OP = 'INSERT' then
    v_action := 'room_created';
  elsif NEW.is_active is distinct from OLD.is_active and NEW.is_active = false then
    v_action := 'room_unlisted';
  else
    v_action := 'room_updated';
  end if;
  insert into public.activity_logs (actor_id, action, entity_type, entity_id, details)
  values (auth.uid(), v_action, 'room', NEW.id::text,
    jsonb_build_object('room_name', NEW.name, 'price', NEW.price, 'guest_capacity', NEW.guests, 'is_active', NEW.is_active));
  return NEW;
end;
$$;
drop trigger if exists rooms_activity_after_insert on public.rooms;
create trigger rooms_activity_after_insert after insert on public.rooms for each row execute function public.capture_room_activity();
drop trigger if exists rooms_activity_after_update on public.rooms;
create trigger rooms_activity_after_update
after update of name, type, price, guests, beds, description, image_url, amenities, is_active on public.rooms
for each row execute function public.capture_room_activity();

create table if not exists public.email_delivery_logs (
  id bigint generated by default as identity primary key,
  booking_id uuid not null references public.bookings(id) on delete cascade,
  event_key text not null,
  recipient text not null,
  status text not null default 'pending' check (status in ('pending', 'sent', 'failed')),
  provider_id text,
  error_message text,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  constraint email_delivery_logs_idempotency unique (booking_id, event_key, recipient)
);
create index if not exists email_delivery_logs_created_idx on public.email_delivery_logs (created_at desc);
alter table public.email_delivery_logs enable row level security;
drop policy if exists email_delivery_logs_read_admin on public.email_delivery_logs;
create policy email_delivery_logs_read_admin on public.email_delivery_logs for select to authenticated using (public.is_admin());
grant select on public.email_delivery_logs to authenticated;

-- Returns available room IDs only; it never exposes other guests' details.
create or replace function public.get_available_room_ids(p_check_in date, p_check_out date)
returns table (room_id bigint)
language plpgsql stable security definer set search_path = public
as $$
begin
  if p_check_in is null or p_check_out is null
     or p_check_in < (now() at time zone 'Asia/Manila')::date
     or p_check_out <= p_check_in then
    raise exception 'Choose valid check-in and check-out dates.';
  end if;
  return query
  select r.id from public.rooms r
  where r.is_active = true
    and not exists (
      select 1 from public.bookings b
      where b.room_id = r.id
        and b.status in ('Pending', 'Confirmed', 'Checked in')
        and b.check_in < p_check_out
        and b.check_out > p_check_in
    )
  order by r.sort_order, r.id;
end;
$$;
revoke all on function public.get_available_room_ids(date, date) from public;
grant execute on function public.get_available_room_ids(date, date) to anon, authenticated;
