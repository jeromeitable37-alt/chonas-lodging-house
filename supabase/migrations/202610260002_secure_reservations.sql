create or replace function public.create_booking(
  p_room_id bigint,
  p_guest_name text,
  p_email text,
  p_phone text,
  p_check_in date,
  p_check_out date,
  p_guests integer,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_room public.rooms%rowtype;
  v_booking public.bookings%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Please sign in before submitting a reservation.';
  end if;
  if p_check_in is null or p_check_out is null
     or p_check_in < (now() at time zone 'Asia/Manila')::date
     or p_check_out <= p_check_in then
    raise exception 'Please choose valid check-in and check-out dates.';
  end if;
  if nullif(btrim(p_guest_name), '') is null
     or nullif(btrim(p_email), '') is null
     or position('@' in p_email) < 2
     or nullif(btrim(p_phone), '') is null then
    raise exception 'Please enter your name, a valid email address, and contact number.';
  end if;
  if p_guests is null or p_guests < 1 then
    raise exception 'Guest count must be at least one.';
  end if;

  -- Lock the room row to serialize concurrent booking requests for that room.
  select * into v_room
  from public.rooms
  where id = p_room_id and is_active = true
  for update;
  if not found then
    raise exception 'This room is not available.';
  end if;
  if p_guests > v_room.guests then
    raise exception 'Guest count exceeds this room capacity.';
  end if;

  if exists (
    select 1
    from public.bookings b
    where b.room_id = p_room_id
      and b.status in ('Pending', 'Confirmed', 'Checked in')
      and b.check_in < p_check_out
      and b.check_out > p_check_in
  ) then
    raise exception 'This room is not available for the selected dates.';
  end if;

  insert into public.bookings (
    user_id, room_id, room_name, guest_name, email, phone,
    check_in, check_out, guests, total, status, notes
  )
  values (
    auth.uid(), v_room.id, v_room.name, btrim(p_guest_name),
    lower(btrim(p_email)), btrim(p_phone), p_check_in, p_check_out,
    p_guests, v_room.price * (p_check_out - p_check_in), 'Pending',
    nullif(btrim(coalesce(p_notes, '')), '')
  )
  returning * into v_booking;

  return jsonb_build_object(
    'id', v_booking.id,
    'reference', v_booking.reference,
    'room_id', v_booking.room_id,
    'room_name', v_booking.room_name,
    'check_in', v_booking.check_in,
    'check_out', v_booking.check_out,
    'guests', v_booking.guests,
    'total', v_booking.total,
    'status', v_booking.status,
    'created_at', v_booking.created_at
  );
end;
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;
revoke all on function public.create_booking(bigint, text, text, text, date, date, integer, text) from public, anon;
grant execute on function public.create_booking(bigint, text, text, text, date, date, integer, text) to authenticated;
