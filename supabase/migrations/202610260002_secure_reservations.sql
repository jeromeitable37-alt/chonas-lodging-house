create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'Guest',
  email text not null unique,
  role text not null default 'guest' check (role in ('guest', 'admin')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_auth_user_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email, role)
  values (
    new.id,
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''), nullif(split_part(coalesce(new.email, ''), '@', 1), ''), 'Guest'),
    coalesce(new.email, ''),
    'guest'
  )
  on conflict (id) do update
    set email = excluded.email,
        full_name = coalesce(
          nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''),
          public.profiles.full_name
        );
  return new;
end;
$$;

drop trigger if exists on_auth_user_profile_created on auth.users;
create trigger on_auth_user_profile_created
after insert or update of email, raw_user_meta_data on auth.users
for each row execute function public.handle_auth_user_profile();

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  name text not null unique,
  type text not null default 'Standard',
  price numeric(12,2) not null check (price > 0),
  guests integer not null default 2 check (guests between 1 and 20),
  beds text not null default '1 double bed',
  description text not null default '',
  image_url text not null,
  amenities jsonb not null default '[]'::jsonb,
  is_active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);

