create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique default ('CH-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))),
  user_id uuid not null references public.profiles(id) on delete restrict,
  room_id bigint not null references public.rooms(id) on delete restrict,
  room_name text not null,
  guest_name text not null,
  email text not null,
  phone text not null,
  check_in date not null,
  check_out date not null,
  guests integer not null check (guests between 1 and 20),
  total numeric(12,2) not null check (total > 0),
  status text not null default 'Pending'
    check (status in ('Pending', 'Confirmed', 'Checked in', 'Completed', 'Cancelled')),
  notes text,
  created_at timestamptz not null default now(),
  constraint bookings_valid_dates check (check_out > check_in)
);

create index if not exists bookings_user_created_idx
  on public.bookings (user_id, created_at desc);
create index if not exists bookings_room_dates_idx
  on public.bookings (room_id, check_in, check_out);
create index if not exists bookings_status_idx
  on public.bookings (status);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.rooms enable row level security;
alter table public.bookings enable row level security;

drop policy if exists profiles_read_self_or_admin on public.profiles;
create policy profiles_read_self_or_admin
  on public.profiles for select to authenticated
  using (id = auth.uid() or public.is_admin());

drop policy if exists profiles_update_own_name on public.profiles;
create policy profiles_update_own_name
  on public.profiles for update to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

drop policy if exists rooms_read_active_or_admin on public.rooms;
create policy rooms_read_active_or_admin
  on public.rooms for select to anon, authenticated
  using (is_active = true or public.is_admin());

drop policy if exists rooms_admin_insert on public.rooms;
create policy rooms_admin_insert
  on public.rooms for insert to authenticated
  with check (public.is_admin());

drop policy if exists rooms_admin_update on public.rooms;
create policy rooms_admin_update
  on public.rooms for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists rooms_admin_delete on public.rooms;
create policy rooms_admin_delete
  on public.rooms for delete to authenticated
  using (public.is_admin());

drop policy if exists bookings_read_owner_or_admin on public.bookings;
create policy bookings_read_owner_or_admin
  on public.bookings for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

drop policy if exists bookings_admin_update on public.bookings;
create policy bookings_admin_update
  on public.bookings for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists bookings_admin_delete on public.bookings;
create policy bookings_admin_delete
  on public.bookings for delete to authenticated
  using (public.is_admin());

